import { Song, PlayerSong } from "@/types";
import { getImageUrl, getVideoUrl } from "./imageUtils";

export const S3_BASE_URL =
  process.env.EXPO_PUBLIC_S3_BASE_URL ||
  "https://audiomelody-prod-storage-oneorg.s3.ap-south-1.amazonaws.com";

export function generateQueueId(prefix = "song"): string {
  return `${prefix}-${Date.now().toString(36)}-${Math.random().toString(36).substring(2, 8)}`;
}

/**
 * Maps a raw Song entity to a full PlayerSong with CDN streaming and image URLs.
 */
export function mapToPlayerSong(song: Song | any, existingQueueId?: string): PlayerSong {
  const songKey = song.songKey || song.song_key;
  const fullVideoKey = song.fullVideoKey || song.full_video_key;
  const videoKey = song.videoKey || song.video_key;
  const imageKey = song.imageKey || song.image_key;

  // Stream URLs point to the master.m3u8 HLS playlist generated by Shaka Packager
  const effectiveAudioKey = songKey || fullVideoKey;
  const audioStreamUrl = effectiveAudioKey
    ? `${S3_BASE_URL}/${effectiveAudioKey}/master.m3u8`
    : "";

  const videoStreamUrl = fullVideoKey
    ? `${S3_BASE_URL}/${fullVideoKey}/master.m3u8`
    : undefined;

  const rawImage =
    imageKey ||
    song.coverUrl ||
    song.posterUrl ||
    song.imageUrl ||
    song.cover_url ||
    song.poster_url;

  const coverUrl =
    getImageUrl(rawImage, {
      width: 400,
      height: 400,
      focus: "auto",
      aspectRatio: "1-1",
    }) ||
    (typeof song.coverUrl === "string" && song.coverUrl.startsWith("http")
      ? song.coverUrl
      : "") ||
    (typeof song.posterUrl === "string" && song.posterUrl.startsWith("http")
      ? song.posterUrl
      : "") ||
    "";

  const posterUrl =
    getImageUrl(rawImage, {
      width: 720,
      height: 720,
      focus: "auto",
      aspectRatio: "1-1",
      quality: 90,
    }) ||
    (typeof song.posterUrl === "string" && song.posterUrl.startsWith("http")
      ? song.posterUrl
      : "") ||
    coverUrl;

  const canvasVideoUrl = videoKey
    ? getVideoUrl(videoKey, {
        width: 540,
        quality: 70,
        format: "mp4",
      })
    : undefined;

  return {
    ...song,
    queueId: existingQueueId || generateQueueId(song.id || "track"),
    audioStreamUrl,
    videoStreamUrl,
    coverUrl,
    posterUrl,
    canvasVideoUrl,
    duration: typeof song.duration === "number" ? song.duration : 0,
    lrclibId: song.lrclibId || song.lrclib_id || undefined,
  };
}

/**
 * Standard Fisher-Yates array shuffling algorithm.
 */
export function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Deduplicates a list of songs by their persistent id.
 */
export function dedupeBySongId<T extends { id: string }>(items: T[]): T[] {
  const seen = new Set<string>();
  return items.filter((item) => {
    if (!item?.id || seen.has(item.id)) return false;
    seen.add(item.id);
    return true;
  });
}

/**
 * Rolling window: keep at most `maxHistory` played songs behind current index.
 * Prevents memory bloat during infinite autoplay / lengthy listening sessions.
 */
export function applyRollingWindow<T>(
  queue: T[],
  currentIndex: number,
  maxHistory = 2,
): { trimmedQueue: T[]; adjustedIndex: number } {
  if (currentIndex <= maxHistory) {
    return { trimmedQueue: queue, adjustedIndex: currentIndex };
  }
  const trimCount = currentIndex - maxHistory;
  const trimmedQueue = queue.slice(trimCount);
  const adjustedIndex = currentIndex - trimCount;
  return { trimmedQueue, adjustedIndex };
}
